"""
نرمال‌سازی متن فارسی/عربی - پایه‌ای برای تشخیص کلمات نامناسب
(app/core/profanity_filter.py)، ولی کاملاً مستقل و قابل استفاده مجدد
برای هر نیاز دیگری که به یکسان‌سازی نویسه‌های فارسی/عربی نیاز دارد.

چرا این نرمال‌سازی لازم است: کاربران فارسی‌زبان اغلب (نه لزوماً از روی
عمد) از نویسه‌های عربی معادل (ي به‌جای ی، ك به‌جای ک، ...) یا کیبورد
عربی استفاده می‌کنند؛ بدون این یکسان‌سازی، یک کلمه با «ي» عربی هرگز با
همان کلمه در فهرست کلمات نامناسب (که با «ی» فارسی ذخیره شده) تطبیق
داده نمی‌شد.
"""
from __future__ import annotations

import re
import unicodedata

# نگاشت نویسه‌های عربی به معادل فارسی رایج‌شان
_ARABIC_TO_PERSIAN_MAP = {
    "\u064a": "\u06cc",  # ي (Arabic Yeh) -> ی (Persian Yeh)
    "\u0649": "\u06cc",  # ى (Arabic Alef Maksura) -> ی
    "\u0643": "\u06a9",  # ك (Arabic Kaf) -> ک (Persian Kaf)
    "\u0629": "\u0647",  # ة (Teh Marbuta) -> ه
    "\u0624": "\u0648",  # ؤ (Waw with Hamza) -> و
    "\u0626": "\u06cc",  # ئ (Yeh with Hamza) -> ی
    "\u0622": "\u0627",  # آ (Alef with Madda) -> ا - چون بعضی کیبوردها آ را با ا+علامت جدا تایپ می‌کنند
    "\u0623": "\u0627",  # أ (Alef with Hamza Above) -> ا
    "\u0625": "\u0627",  # إ (Alef with Hamza Below) -> ا
}

# اعراب/تشکیل عربی (فتحه، ضمه، کسره، تنوین، شدّ، سکون، ...) - نویسه‌های
# ترکیبی (Combining Marks) که معنای نوشتاری ندارند و فقط تلفظ را نشان می‌دهند
_ARABIC_DIACRITICS_PATTERN = re.compile("[\u064b-\u065f\u0670\u06d6-\u06ed]")

_ZERO_WIDTH_NON_JOINER = "\u200c"
_TATWEEL_KASHIDA = "\u0640"  # ـ - نویسه کشیدگی بصری، بدون معنای نوشتاری

# کاراکترهای «نویز» که اغلب برای دورزدن فیلتر کلمات، بین حروف یک کلمه
# چسبانده می‌شوند (نقطه، خط تیره، زیرخط، ستاره، و انواع فاصله)
_NOISE_CHARS_PATTERN = re.compile(r"[.\-_*+~`'\"!@#$%^&()\[\]{}|\\/:;,<>?=\s]+")


def normalize_persian_text(text: str) -> str:
    """
    نرمال‌سازی کامل: یکسان‌سازی نویسه‌های عربی/فارسی، حذف اعراب/تشکیل،
    حذف کشیده، تبدیل نیم‌فاصله به فاصله معمولی (برای این‌که مرز کلمه در
    توکن‌سازی درست تشخیص داده شود)، و جمع‌کردن فاصله‌های تکراری.
    خروجی: متن نرمال‌شده، آماده برای توکن‌سازی/مقایسه - نه لزوماً برای
    نمایش به کاربر.
    """
    # Unicode NFKC - یکسان‌سازی اشکال ترکیبی/سازگاری نویسه‌ها
    text = unicodedata.normalize("NFKC", text)

    for arabic_char, persian_char in _ARABIC_TO_PERSIAN_MAP.items():
        text = text.replace(arabic_char, persian_char)

    text = _ARABIC_DIACRITICS_PATTERN.sub("", text)
    text = text.replace(_TATWEEL_KASHIDA, "")
    # نیم‌فاصله را به فاصله معمولی تبدیل می‌کنیم (نه حذف کامل) - چون در
    # «می‌روم» نیم‌فاصله در واقع مرز دو تکواژ است؛ برای تشخیص کلمه
    # نامناسب، رفتار به‌عنوان فاصله معمولی امن‌تر و کافی است.
    text = text.replace(_ZERO_WIDTH_NON_JOINER, " ")
    text = re.sub(r"\s+", " ", text).strip()

    return text


def collapse_repeated_letters(word: str) -> str:
    """
    حروف تکراری متوالی را به یک حرف تقلیل می‌دهد ("کوووووس" -> "کوس") -
    برای خنثی‌کردن کشیدن حروف (چه با کشیده ـ، چه با تکرار خودِ حرف) به
    قصد فرار از فیلتر. چون زبان فارسی معمولاً حرف دوتایی متوالی طبیعی
    ندارد، این تقلیل خطر بالایی برای متن‌های سالم ایجاد نمی‌کند.
    """
    return re.sub(r"(.)\1+", r"\1", word)


def strip_noise_characters(text: str) -> str:
    """
    همه نویزهای بین‌حرفی (نقطه، خط‌تیره، فاصله، ...) را کاملاً حذف می‌کند
    - برای تشخیص شکل «شکسته‌شده عمدی» یک کلمه (مثل «ک.ی.ر» یا «ک ی ر»).
    فقط برای بررسی کمکی «آیا این چسبیده، شکل شکسته یک کلمه کوتاه خاص
    است» به کار می‌رود - نه برای توکن‌سازی معمول متن.
    """
    return _NOISE_CHARS_PATTERN.sub("", text)


def tokenize(normalized_text: str) -> list[str]:
    """متن نرمال‌شده (normalize_persian_text) را بر اساس فاصله و علائم نگارشی رایج به توکن‌ها می‌شکند."""
    return [t for t in re.split(r"[\s.,!?؟،؛:\-_/\\|]+", normalized_text) if t]
